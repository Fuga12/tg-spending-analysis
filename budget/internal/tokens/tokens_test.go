package tokens

import (
	"testing"

	"github.com/shopspring/decimal"
)

func TestExtract(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		// Разбор сумм — контракт: с ним сверяется всё, что вернула модель.
		{"600 лимонад", []string{"600"}},
		{"такси 450", []string{"450"}},
		{"1 200 доставка", []string{"1200"}},
		{"1200,50 продукты", []string{"1200.50"}},
		{"1200.50 продукты", []string{"1200.50"}},
		{"3к аренда", []string{"3000"}},
		{"1.5к бензин", []string{"1500"}},
		{"500р кофе", []string{"500"}},
		{"вчера пятёрочка 1200 и такси 400", []string{"1200", "400"}},
		{"кофе", nil},
		{"0 тест", []string{"0"}},

		// Дополнительно: то, что реально пишут в чат.
		{"", nil},
		{"1200₽ продукты", []string{"1200"}},
		{"1 200 руб. доставка", []string{"1200"}},
		{"теле2 500", []string{"500"}},
		{"3кг картошки 250", []string{"3", "250"}},
		{"скинул ей 5К", []string{"5000"}},
		{"пятёрочка 1200, такси 400", []string{"1200", "400"}},
		{"1 200 500 квартира", []string{"1200500"}},
		{"обед 350 и кофе 350", []string{"350", "350"}},
		{"1200,5 продукты", []string{"1200.5"}},

		// Две суммы подряд не должны слипаться в одну: голова разделителя
		// тысяч — не больше трёх цифр.
		{"1200 400", []string{"1200", "400"}},
		{"такси 1200 400", []string{"1200", "400"}},
		{"12345 678", []string{"12345", "678"}},
		{"1 000 000 квартира", []string{"1000000"}},

		// Сумма, слипшаяся со словом, — всё равно сумма.
		{"такси400", []string{"400"}},
		{"на1200 продукты", []string{"1200"}},

		// А вот это суммами не является: иначе деградированный путь
		// возьмёт первое число и запишет трату на 4 ₽ или на 19 ₽.
		{"4g интернет 500", []string{"500"}},
		{"в 19:30 кофе 200", []string{"200"}},
		{"5gb трафика 300", []string{"300"}},

		{"5 тыс аренда", []string{"5000"}},
		{"5 тыс. аренда", []string{"5000"}},
		{"1 200 доставка", []string{"1200"}},
		{"1 200 доставка", []string{"1200"}},

		// Известное ограничение правила «пробел разделяет тысячи» («1 200» → 1200):
		// «600 100» неотличимо от разделителя тысяч и склеивается.
		{"600 100", []string{"600100"}},
	}

	for _, c := range cases {
		t.Run(c.in, func(t *testing.T) {
			got := Extract(c.in)
			if len(got) != len(c.want) {
				t.Fatalf("Extract(%q) = %v, ожидалось %v", c.in, got, c.want)
			}
			for i := range got {
				want := decimal.RequireFromString(c.want[i])
				if !got[i].Equal(want) {
					t.Errorf("Extract(%q)[%d] = %s, ожидалось %s", c.in, i, got[i], want)
				}
			}
		})
	}
}

func TestStrip(t *testing.T) {
	// Strip даёт описание траты — и после разбора моделью, и без неё.
	cases := []struct{ in, want string }{
		{"600 лимонад", "лимонад"},
		{"500р кофе", "кофе"},
		{"1 200 руб. доставка", "доставка"},
		{"такси 450", "такси"},
		{"кофе", "кофе"},
		{"1200₽", ""},
		{"вчера пятёрочка 1200 и такси 400", "вчера пятёрочка и такси"},
	}
	for _, c := range cases {
		if got := Strip(c.in); got != c.want {
			t.Errorf("Strip(%q) = %q, ожидалось %q", c.in, got, c.want)
		}
	}
}

func TestFindSpans(t *testing.T) {
	// Границы нужны деградированному пути: описание — текст без суммы.
	got := find("500р кофе")
	if len(got) != 1 {
		t.Fatalf("найдено %d сумм, ожидалась одна", len(got))
	}
	if got[0].Start != 0 || got[0].End != 4 {
		t.Errorf("границы суммы = [%d,%d), ожидалось [0,4)", got[0].Start, got[0].End)
	}
}

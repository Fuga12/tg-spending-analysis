-- +goose Up
-- У категории может быть адресат-человек, а не только «плательщику» или
-- «на двоих». «Косметика — всегда Уле» верно независимо от того, кто платил,
-- и относительными значениями это не выражается.
--
-- В транзакции по-прежнему лежит payer/partner/both: адресат разрешается
-- в момент записи, от того, кто платит. Схема трат не меняется.
-- Без внешнего ключа намеренно. Во-первых, адресата можно назначить раньше,
-- чем человек впервые напишет боту и заведётся в users. Во-вторых, ссылка
-- делает categories дочерней таблицей users, и любой truncate users cascade
-- сносит вместе с людьми весь список категорий.
--
-- Чужой id сюда не попадёт: веб сверяет адресата с whitelist, а это проверка
-- строже, чем существование строки в users.
alter table categories add column default_user_id bigint;


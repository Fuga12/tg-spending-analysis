-- +goose Up
-- Подсказка уходит в описание категории внутри JSON-схемы: пояснения там
-- заметно поднимают точность разбора (plan.md §6). Правится на сайте — это
-- единственный способ научить модель различать то, что путает именно нас.
alter table categories add column hint text not null default '';

update categories set hint = case name
    when 'Продукты'            then 'магазины, супермаркеты, еда домой'
    when 'Кафе и рестораны'    then 'поесть вне дома: кафе, бар, кофейня, столовая'
    when 'Доставка еды'        then 'готовая еда домой: пицца, суши, доставка из ресторана'
    when 'Транспорт'           then 'автобус, метро, электричка, бензин, парковка'
    when 'Такси'               then 'такси и каршеринг'
    when 'Жильё'               then 'аренда, ипотека, ремонт'
    when 'Коммуналка'          then 'ЖКХ, электричество, вода, отопление'
    when 'Связь и интернет'    then 'мобильная связь, домашний интернет, подписки на связь'
    when 'Здоровье'            then 'аптека, врачи, анализы, стоматология'
    when 'Одежда'              then 'одежда, обувь, аксессуары'
    when 'Хобби и развлечения' then 'кино, игры, спорт, книги, концерты, подписки'
    when 'Подарки'             then 'подарки другим людям, цветы, сувениры'
    when 'Дом и быт'           then 'бытовая химия, посуда, мебель, инструменты, товары для дома'
    when 'Прочее'              then 'то, что не подходит ни к одной другой категории'
    else ''
end;

-- +goose Down
alter table categories drop column hint;

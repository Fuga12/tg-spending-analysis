-- +goose Up
-- Своё фото профиля. Telegram отдаёт фото не всем: у кого-то его нет вовсе,
-- у кого-то оно закрыто настройками приватности — ботом такой аккаунт виден
-- без фотографии, и в списке остаются инициалы. Менять настройки Telegram
-- ради кружка в бюджете никто не станет, поэтому фото ставится на сайте.
--
-- Байты лежат в базе, а не файлом на диске: бэкап у нас — дамп базы, и файл
-- рядом с ним в него не попадёт, то есть потеряется при первом же
-- восстановлении. Картинка маленькая (256×256 JPEG, десятки килобайт) —
-- дамп это переживёт.
alter table users
    add column avatar        bytea,
    -- Он же версия картинки: уезжает в URL и сбрасывает кэш браузера, иначе
    -- новое фото полсуток не видно из-за Cache-Control на самой картинке.
    add column avatar_set_at timestamptz;

-- +goose Down
alter table users drop column avatar_set_at, drop column avatar;
